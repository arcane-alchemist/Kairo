import { build } from 'astro';
import { cpSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { PAGE_HEADERS } from '../serverless/security.js';
await build({});
const files = ['styles.css', 'icon.svg', 'manifest.webmanifest', 'offline.html', 'icon-192.png', 'icon-512.png', 'favicon.svg', 'ntl-logo.png'];
for (const file of files) cpSync(`frontend/${file}`, `dist/${file}`);
const assets = readdirSync('dist/_astro', {recursive: true}).filter(file => statSync(`dist/_astro/${file}`).isFile()).map(file => `/_astro/${file}`).sort();
const hash = createHash('sha256').update(readFileSync('dist/index.html')).update(readFileSync('frontend/sw.js')).update(JSON.stringify(assets));
for (const file of files) hash.update(readFileSync(`frontend/${file}`));
const version = hash.digest('hex').slice(0, 12);
const worker = readFileSync('frontend/sw.js', 'utf8').replace("'kairo-studio-build'", `'kairo-studio-${version}'`).replace('const BUILD_ASSETS = [];', `const BUILD_ASSETS = ${JSON.stringify(assets)};`);
writeFileSync('dist/sw.js', worker);
writeFileSync('dist/_headers', '/*\n' + Object.entries(PAGE_HEADERS).map(([name,value]) => `  ${name}: ${value}`).join('\n') + '\n/_astro/*\n  Cache-Control: public, max-age=31536000, immutable\n');
console.log('Astro website built in dist/');
